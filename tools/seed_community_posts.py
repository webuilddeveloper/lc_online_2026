def post_json(path: str, payload: dict) -> dict:
    url = f"{API_BASE}{path}"
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main() -> int:
    print(f"API: {API_BASE}")
    print(f"Profile: {PROFILE_CODE}")
    print(f"Target posts: {POST_COUNT}")

    subtopic_res = post_json("/m/topic/subTopic/read", {})
    if subtopic_res.get("status") != "S":
        print("Failed to load subTopics:", subtopic_res)
        return 1

    subtopics = subtopic_res.get("objectData") or []
    if not subtopics:
        print("No subTopics found")
        return 1

    success = 0
    failed = 0

    for i in range(POST_COUNT):
        topic = subtopics[i % len(subtopics)]
        description = POSTS[i % len(POSTS)]
        payload = {
            "profileCode": PROFILE_CODE,
            "description": description,
            "category": topic.get("code", ""),
            "subTopic": topic.get("code", ""),
            "subTopicTitle": topic.get("title", ""),
            "gallery": [],
        }

        try:
            result = post_json("/m/community/create", payload)
            if result.get("status") == "S":
                success += 1
                code = ""
                obj = result.get("objectData")
                if isinstance(obj, dict):
                    code = obj.get("code", "")
                elif isinstance(obj, list) and obj and isinstance(obj[0], dict):
                    code = obj[0].get("code", "")
                print(f"[{i + 1}/{POST_COUNT}] OK {code} | {topic.get('title', '')[:40]}")
            else:
                failed += 1
                print(
                    f"[{i + 1}/{POST_COUNT}] FAIL: {result.get('message', result)}"
                )
        except Exception as exc:
            failed += 1
            print(f"[{i + 1}/{POST_COUNT}] ERROR: {exc}")

        time.sleep(0.15)

    print(f"Done. success={success}, failed={failed}")
    return 0 if failed == 0 else 2


if __name__ == "__main__":
    sys.exit(main())
